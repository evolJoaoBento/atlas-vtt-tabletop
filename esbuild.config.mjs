import esbuild from 'esbuild';
/* global process -- this build script runs under Node */

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
  banner: { js: '/* Atlas VTT Extension - Tabletop. Generated by esbuild; see the source repository. */' },
  entryPoints: ['main.ts'],
  bundle: true,
  external: ['obsidian', 'electron', '@codemirror/state', '@codemirror/view'],
  format: 'cjs',
  target: 'es2020',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  // Atlas's copied React components (src/atlasPort/app) use the automatic JSX runtime, as in Atlas.
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': prod ? '"production"' : '"development"' },
  minify: prod,
  loader: { '.png': 'binary', '.mp3': 'binary' },
  outfile: 'main.js',
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
