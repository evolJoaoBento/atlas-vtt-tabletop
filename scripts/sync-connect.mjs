// Tabletop's copies of what Connect for Atlas VTT owns:
// - packages/atlas-shared and packages/atlas-host, copied byte for byte from a Connect checkout;
// - src/connectWire.ts, generated from Connect's src/app/online/scene/boardTypes.ts (a header line, then the file).
// connect-sync.json records the Connect commit and a hash of every copied file, so a hand edit is found offline.
//
// Usage:
//   node scripts/sync-connect.mjs --connect <Connect checkout>          copy and generate
//   node scripts/sync-connect.mjs --check [--root <a copy of Tabletop>] check, offline, that nothing was edited by hand
//   node scripts/sync-connect.mjs --check --connect <Connect checkout>  also compare with the checkout
/* global process, console -- this script runs under Node */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const value = (flag) => { const at = args.indexOf(flag); return at >= 0 ? args[at + 1] : undefined; };
const root = path.resolve(value('--root') ?? path.join(path.dirname(fileURLToPath(import.meta.url)), '..'));
const connect = value('--connect') ? path.resolve(value('--connect')) : null;
const check = args.includes('--check');

const PACKAGES = ['packages/atlas-shared', 'packages/atlas-host'];
const WIRE_SOURCE = 'src/app/online/scene/boardTypes.ts';
const WIRE = 'src/connectWire.ts';
const RECORD = 'connect-sync.json';
const header = (commit) => `// Generated by scripts/sync-connect.mjs from Connect ${commit.slice(0, 7)} ${WIRE_SOURCE}. Do not edit; run npm run sync:connect.\n`;

/** sha256 of a file; CRLF counts as LF, so a Windows checkout cannot change a hash (Connect's `scripts/vendorHash.mjs`). */
function hashFile(file) {
  return createHash('sha256').update(Buffer.from(readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), 'utf8')).digest('hex');
}
/** Every file under `dir`, as forward-slash paths relative to `base`. */
function filesUnder(base, dir) {
  const found = [];
  const walk = (at) => {
    for (const name of readdirSync(at).sort()) {
      const full = path.join(at, name);
      if (statSync(full).isDirectory()) walk(full);
      else found.push(path.relative(base, full).split(path.sep).join('/'));
    }
  };
  if (existsSync(path.join(base, dir))) walk(path.join(base, dir));
  return found;
}
const text = (file) => readFileSync(file, 'utf8').replace(/\r\n/g, '\n');

if (!check) {
  if (!connect) throw new Error('Usage: node scripts/sync-connect.mjs --connect <Connect checkout> | --check [--connect <Connect checkout>]');
  const git = (...rest) => execFileSync('git', ['-C', connect, ...rest], { encoding: 'utf8' }).trim();
  const dirty = git('status', '--porcelain', '--', 'packages', WIRE_SOURCE);
  if (dirty) throw new Error(`Connect has uncommitted changes in what is copied:\n${dirty}\nCommit them in Connect first.`);
  const commit = git('rev-parse', 'HEAD');
  for (const dir of PACKAGES) {
    rmSync(path.join(root, dir), { recursive: true, force: true });
    cpSync(path.join(connect, dir), path.join(root, dir), { recursive: true });
  }
  writeFileSync(path.join(root, WIRE), header(commit) + text(path.join(connect, WIRE_SOURCE)));
  const files = {};
  for (const file of [...PACKAGES.flatMap((dir) => filesUnder(root, dir)), WIRE]) files[file] = hashFile(path.join(root, file));
  writeFileSync(path.join(root, RECORD), `${JSON.stringify({ connect: { commit }, files }, null, 2)}\n`);
  console.log(`Copied ${Object.keys(files).length - 1} package files and generated ${WIRE} from Connect ${commit.slice(0, 7)}.`);
} else {
  const record = JSON.parse(readFileSync(path.join(root, RECORD), 'utf8'));
  const problems = [];
  for (const [file, hash] of Object.entries(record.files)) {
    const full = path.join(root, file);
    if (!existsSync(full)) problems.push(`missing: ${file}`);
    else if (hashFile(full) !== hash) problems.push(`changed: ${file}`);
  }
  for (const file of PACKAGES.flatMap((dir) => filesUnder(root, dir))) if (!Object.hasOwn(record.files, file)) problems.push(`not from the sync: ${file}`);
  if (connect) {
    const same = (file, theirs) => { if (text(path.join(root, file)) !== theirs) problems.push(`differs from Connect: ${file}`); };
    same('packages/atlas-shared/SOURCE.json', text(path.join(connect, 'packages/atlas-shared/SOURCE.json')));
    same(WIRE, header(record.connect.commit) + text(path.join(connect, WIRE_SOURCE)));
    for (const dir of PACKAGES) for (const file of filesUnder(connect, dir)) {
      if (!existsSync(path.join(root, file))) problems.push(`missing: ${file}`);
      else if (hashFile(path.join(root, file)) !== hashFile(path.join(connect, file))) problems.push(`differs from Connect: ${file}`);
    }
  }
  if (problems.length > 0) {
    for (const problem of [...new Set(problems)]) console.error(problem);
    console.error('Tabletop\'s copies of Connect\'s files are out of step. Fix it in Connect, then run `npm run sync:connect -- --connect <checkout>`; never edit them here.');
    process.exit(1);
  }
  console.log(`packages and ${WIRE} match Connect ${record.connect.commit.slice(0, 7)}${connect ? ' (and the checkout)' : ''}.`);
}
