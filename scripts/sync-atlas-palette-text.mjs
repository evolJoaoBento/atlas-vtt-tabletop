// Usage: node scripts/sync-atlas-palette-text.mjs [path to an Atlas 0.19 source checkout] (default ../atlas-vtt-0.19-ref)
// Writes src/atlasPort/atlasTextPalette.ts: Atlas 0.19's texts (en, ru, zh) for every key the copies of Atlas 0.19's files under
// src/atlasPort/app use (the command palette and its settings pages, with what they reach). The plain text sync
// (sync-atlas-port.mjs) is the 0.15 floor's and lacks them; these texts win over the floor's of the same key (atlasText.ts).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ref = `${process.argv[2] ?? '../atlas-vtt-0.19-ref'}/src/app/i18n/locales`;
const LANGS = ['en', 'ru', 'zh'];

/** Every key and text of one language: each locale file is a TS object literal, read by running it. */
function textsOf(lang) {
  const all = {};
  for (const file of readdirSync(join(ref, lang))) {
    if (!file.endsWith('.ts') || file === 'index.ts') continue;
    let src = readFileSync(join(ref, lang, file), 'utf8');
    src = src.replace(/^import .*$/gm, '').replace(/export const (\w+)(?:: [\w<>, ]+)? =/, 'const $1 =').replace(/\}\s*(?:as const)?\s*(?:satisfies[^;]*)?;?\s*$/, '}');
    const name = /const (\w+) =/.exec(src)?.[1];
    if (!name) continue;
    try { Object.assign(all, new Function(`${src}; return ${name};`)()); } catch (error) { console.warn(`skipped ${lang}/${file}: ${error.message}`); }
  }
  return all;
}
const texts = Object.fromEntries(LANGS.map((lang) => [lang, textsOf(lang)]));

/** The copies from Atlas 0.19 (their first line names the version). */
function* copies(dir) {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) yield* copies(path);
    else if (/\.tsx?$/.test(entry) && readFileSync(path, 'utf8').split('\n', 1)[0].includes('@ 0.19.0')) yield path;
  }
}
const used = new Set();
const spaces = new Set();
for (const path of copies('src/atlasPort/app')) {
  const source = readFileSync(path, 'utf8');
  for (const match of source.matchAll(/['"`]([a-zA-Z][\w-]*(?:\.[\w-]+)+)['"`]/g)) used.add(match[1]);
  for (const match of source.matchAll(/\bt\w*\(\s*`([\w-]+)\./g)) spaces.add(match[1]);
}
const keys = Object.keys(texts.en).filter((key) => {
  const base = key.replace(/\.(touch|mobile)$/, '');
  return used.has(key) || used.has(base) || spaces.has(key.split('.')[0]) && [...spaces].some((space) => key.startsWith(`${space}.`));
}).sort();
const out = Object.fromEntries(LANGS.map((lang) => [lang, Object.fromEntries(keys.filter((key) => texts[lang][key] !== undefined).map((key) => [key, texts[lang][key]]))]));
const body = `// Generated by scripts/sync-atlas-palette-text.mjs from Atlas 0.19's src/app/i18n/locales/{en,ru,zh} (AGPL-3.0): the texts the copies of
// Atlas 0.19's command palette and settings pages (and what they reach) use. The synced snapshot (the floor, 0.15) lacks some and words
// others differently; these win (atlasText.ts).
import type { AtlasMessage } from './atlasText';

export const ATLAS_TEXT_PALETTE: Readonly<Record<string, Readonly<Record<string, AtlasMessage>>>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync('src/atlasPort/atlasTextPalette.ts', body);
console.log(keys.length, 'keys');
